function normalizeSpecies(value: string) {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

export function getBreedOptions(
  species: string
): readonly string[] {
  switch (normalizeSpecies(species)) {
    case "chien":
    case "dog":
      return DOG_BREEDS;

    case "chat":
    case "cat":
      return CAT_BREEDS;

    case "cheval":
    case "horse":
      return HORSE_BREEDS;

    case "oiseau":
    case "bird":
      return BIRD_BREEDS;

    case "lapin":
    case "rabbit":
      return RABBIT_BREEDS;

    default:
      return [];
  }
}

export function getBreedLabel(
  species: string
) {
  switch (normalizeSpecies(species)) {
    case "oiseau":
    case "bird":
      return "Espèce / variété";

    default:
      return "Race";
  }
}
